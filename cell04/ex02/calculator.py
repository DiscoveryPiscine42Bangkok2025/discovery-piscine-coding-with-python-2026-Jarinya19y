#!/usr/bin/env python3
fst_num = int(input("Gimme first number : "))
sec_num = int(input("Gimme second number : "))
print("Thank you!")

print(fst_num, "+", sec_num, "=", fst_num + sec_num)
print(fst_num, "-", sec_num, "=", fst_num - sec_num)
print(fst_num, "/", sec_num, "=", fst_num // sec_num)
print(fst_num, "*", sec_num, "=", fst_num * sec_num)